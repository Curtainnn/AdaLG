import torch
import torch.nn as nn
from torch import Tensor

from layers.causal_ode import CausalODEFeaturePropagation


MODEL_NAME = 'astgi'
MODEL_ALIASES = ('ASTGI',)
SUPPORTS_MASK_ARGS = True


def _build_mlp(dims, dropout=0.1):
    layers = []
    for i in range(len(dims) - 2):
        layers.append(nn.Linear(dims[i], dims[i + 1]))
        layers.append(nn.ReLU())
        layers.append(nn.Dropout(dropout))
    layers.append(nn.Linear(dims[-2], dims[-1]))
    return nn.Sequential(*layers)


class Model(nn.Module):
    supports_mask_args = True

    def __init__(self, configs):
        super().__init__()
        self.configs = configs
        self.n_vars = int(configs.enc_in)
        self.d_model = int(configs.d_model)
        self.dropout = float(configs.dropout)
        self.d_c = int(getattr(configs, 'astgi_channel_dim', 24))
        self.d_t = int(getattr(configs, 'astgi_time_dim', 24))
        self.mlp_ratio = float(getattr(configs, 'astgi_mlp_ratio', 2.0))
        self.query_chunk_size = max(int(getattr(configs, 'astgi_query_chunk_size', 1024)), 1)
        self.use_norm = bool(getattr(configs, 'use_norm', False))
        d_coord = self.d_c + self.d_t

        self.channel_embedding = nn.Embedding(self.n_vars, self.d_c)
        self.time_encoder = _build_mlp([1, self.d_t * 2, self.d_t], self.dropout)
        self.value_encoder = _build_mlp([1, self.d_model * 2, self.d_model], self.dropout)

        # KNN neighbor propagation is removed. Point features are propagated by
        # a variable-level dynamic causal matrix generated by CausalODE.
        self.causal_ode = CausalODEFeaturePropagation(
            hidden_dim=self.d_model,
            num_vars=self.n_vars,
            state_dim=int(getattr(configs, 'causal_ode_state_dim', 32)),
            ode_hidden=int(getattr(configs, 'causal_ode_hidden', 128)),
            constraint_strength=float(getattr(configs, 'causal_ode_constraint_strength', 0.0)),
            h_weight=float(getattr(configs, 'causal_ode_h_weight', 1e-3)),
            l1_weight=float(getattr(configs, 'causal_ode_l1_weight', 1e-4)),
            diag_weight=float(getattr(configs, 'causal_ode_diag_weight', 1e-3)),
            laplacian_weight=float(getattr(configs, 'causal_ode_laplacian_weight', 1e-4)),
            adjacency_scale=float(getattr(configs, 'causal_ode_adjacency_scale', 1.0)),
            gate_init=float(getattr(configs, 'causal_ode_gate_init', -4.0)),
            ode_steps=int(getattr(configs, 'causal_ode_steps', 8)),
            dropout=self.dropout,
        )

        self.query_kernel = _build_mlp([d_coord + self.d_model, int(self.d_model * self.mlp_ratio), 1], self.dropout)
        self.value_mlp = _build_mlp([self.d_model, self.d_model, self.d_model], self.dropout)
        self.regression_head = _build_mlp([self.d_model, int(self.d_model * self.mlp_ratio), 1], self.dropout)

    def _normalize_dense_input(self, x, x_mask=None):
        valid_mask = x_mask.to(dtype=torch.bool) if x_mask is not None else torch.isfinite(x)
        safe_x = torch.nan_to_num(x, nan=0.0, posinf=0.0, neginf=0.0)
        valid_count = valid_mask.sum(dim=1, keepdim=True).clamp_min(1).to(safe_x.dtype)
        means = (safe_x * valid_mask.to(safe_x.dtype)).sum(dim=1, keepdim=True) / valid_count
        centered_x = torch.where(valid_mask, safe_x - means, torch.zeros_like(safe_x))
        variance = centered_x.pow(2).sum(dim=1, keepdim=True) / valid_count
        stdev = torch.sqrt(variance + 1e-5)
        normalized_x = centered_x / stdev
        return normalized_x, means.detach(), stdev

    def _prepare_time_mark(self, x, x_mark):
        if x_mark is None:
            batch_size, seq_len = x.shape[0], x.shape[1]
            return (
                torch.arange(seq_len, device=x.device, dtype=x.dtype)
                .view(1, seq_len, 1)
                .expand(batch_size, -1, -1)
            )
        if x_mark.dim() == 2:
            return x_mark.unsqueeze(-1).to(dtype=x.dtype)
        return x_mark.to(dtype=x.dtype)

    def _prepare_mask(self, x, x_mask):
        if x_mask is None:
            return torch.isfinite(x)
        if x_mask.dim() == 2:
            x_mask = x_mask.unsqueeze(-1).expand(-1, -1, x.shape[-1])
        elif x_mask.dim() == 3 and x_mask.shape[-1] == 1:
            x_mask = x_mask.expand(-1, -1, x.shape[-1])
        return x_mask.to(dtype=torch.bool)

    def get_regularization_loss(self):
        return self.causal_ode.get_regularization_loss()

    def _query_all_history_batchwise(
        self,
        query_coord: Tensor,
        hist_coord: Tensor,
        hist_hidden: Tensor,
        query_batch_idx: Tensor,
        hist_batch_idx: Tensor,
        batch_size: int,
    ) -> Tensor:
        """Full history attention for query decoding; no cdist/topk KNN is used."""
        if query_coord.shape[0] == 0:
            return hist_hidden.new_zeros(0, self.d_model)
        query_hidden = hist_hidden.new_zeros(query_coord.shape[0], self.d_model)
        for batch_id in range(batch_size):
            q_global_idx = torch.nonzero(query_batch_idx == batch_id, as_tuple=False).squeeze(-1)
            if q_global_idx.numel() == 0:
                continue
            h_global_idx = torch.nonzero(hist_batch_idx == batch_id, as_tuple=False).squeeze(-1)
            if h_global_idx.numel() == 0:
                continue
            h_coord = hist_coord[h_global_idx]
            h_hidden = hist_hidden[h_global_idx]
            h_hidden_value = self.value_mlp(h_hidden)
            for start in range(0, int(q_global_idx.numel()), self.query_chunk_size):
                end = min(start + self.query_chunk_size, int(q_global_idx.numel()))
                q_idx = q_global_idx[start:end]
                q_coord = query_coord[q_idx]
                rel = q_coord.unsqueeze(1) - h_coord.unsqueeze(0)
                h_expand = h_hidden.unsqueeze(0).expand(q_coord.shape[0], -1, -1)
                score_input = torch.cat([rel, h_expand], dim=-1)
                attn = torch.softmax(self.query_kernel(score_input).squeeze(-1), dim=-1)
                query_hidden[q_idx] = torch.sum(attn.unsqueeze(-1) * h_hidden_value.unsqueeze(0), dim=1)
        return query_hidden

    def forward(self, x, x_mark, y_mark, x_mask=None, y_mask=None, **kwargs):
        x_mask = self._prepare_mask(x, x_mask)
        x_mark = self._prepare_time_mark(x, x_mark)
        if self.use_norm:
            x, means, stdev = self._normalize_dense_input(x, x_mask=x_mask)
        else:
            x = torch.nan_to_num(x, nan=0.0, posinf=0.0, neginf=0.0)
            means = None
            stdev = None

        batch_size, _, num_vars = x.shape
        pred_len = y_mark.shape[1]

        valid_indices = x_mask.nonzero(as_tuple=False)
        if valid_indices.numel() == 0:
            return x.new_zeros((batch_size, pred_len, num_vars))

        batch_idx = valid_indices[:, 0]
        row_idx = valid_indices[:, 1]
        var_idx = valid_indices[:, 2]
        time_denom = float(max(int(getattr(self.configs, 'seq_len', x.shape[1])) - 1, 1))

        point_values = x[batch_idx, row_idx, var_idx].unsqueeze(-1)
        raw_point_times = x_mark[batch_idx, row_idx, 0]
        point_times = raw_point_times.unsqueeze(-1) / time_denom

        point_channel = self.channel_embedding(var_idx)
        point_time = self.time_encoder(point_times)
        point_coord = torch.cat([point_channel, point_time], dim=-1)
        point_hidden = self.value_encoder(point_values)

        point_hidden = self.causal_ode(
            point_feature=point_hidden,
            batch_idx=batch_idx.long(),
            time_idx=raw_point_times,
            var_idx=var_idx.long(),
            batch_size=batch_size,
            num_vars=num_vars,
            seq_len=int(getattr(self.configs, 'seq_len', x.shape[1])),
        )

        query_times = y_mark[:, :, 0].reshape(-1, 1).to(dtype=x.dtype) / time_denom
        query_times = query_times.repeat_interleave(num_vars, dim=0)
        query_vars = torch.arange(num_vars, device=x.device).repeat(batch_size * pred_len)
        query_batch_idx = torch.arange(batch_size, device=x.device).repeat_interleave(pred_len * num_vars)

        query_channel = self.channel_embedding(query_vars)
        query_time = self.time_encoder(query_times)
        query_coord = torch.cat([query_channel, query_time], dim=-1)

        query_hidden = self._query_all_history_batchwise(
            query_coord=query_coord,
            hist_coord=point_coord,
            hist_hidden=point_hidden,
            query_batch_idx=query_batch_idx,
            hist_batch_idx=batch_idx,
            batch_size=batch_size,
        )
        pred = self.regression_head(query_hidden).view(batch_size, pred_len, num_vars)
        if self.use_norm:
            pred = pred * stdev + means

        if str(getattr(self.configs, 'features', 'M')).upper() == 'MS':
            return pred[:, :, -1:]
        return pred
